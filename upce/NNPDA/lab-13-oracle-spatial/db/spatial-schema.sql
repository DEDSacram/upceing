-- Lab 13 spatial schema (Oracle XE 21c). Runs as APP_USER on first start.
-- SDO_GEOMETRY: (gtype, srid, point, elem_info, ordinates)

CREATE TABLE cities (
  id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100) NOT NULL,
  geom MDSYS.SDO_GEOMETRY NOT NULL
);

CREATE TABLE roads (
  id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100) NOT NULL,
  geom MDSYS.SDO_GEOMETRY NOT NULL
);

